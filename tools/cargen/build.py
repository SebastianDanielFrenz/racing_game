"""Build racing_game's own car models:  python3 tools/cargen/build.py [model_id ...]

Writes data/models/<id>/<id>.glb (LOD0), <id>_lod1.glb, <id>_lod2.glb, <id>.rig.json (physics_sim.rig/1, same
convention as physics_sim's data/models), <id>.flow.json (exterior CFD surface
selection, pinned to the LOD0 GLB's sha256) and <id>.cockpit.json (rg.cockpit/1),
plus data/models/index.json. Stdlib only (plus physics_sim's assetgen, read-only).
Deterministic: same code -> byte-identical files.
"""
import hashlib
import importlib
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import cargen  # noqa: E402  (puts assetgen on sys.path)
from cargen import quality as Q  # noqa: E402

OUT = os.path.join(cargen.REPO, "data", "models")
MODELS = ["pico", "ventura_gt", "runabout_t"]


def write_json(path, obj):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=2)
        f.write("\n")


QUALITY_TIERS = {
    "note": "Suggested use of the LOD files per graphics quality setting (not wired into the game yet). The garage "
            "and the cockpit camera always use LOD0. lod_switch_m = camera distance at which LOD1, then LOD2 "
            "take over; transparent_lenses false = draw lamp lenses (role lens) opaque or skip them.",
    "high": {"lod_switch_m": [15, 60], "transparent_lenses": True},
    "medium": {"lod_switch_m": [10, 40], "transparent_lenses": True},
    "low": {"lod_switch_m": [5, 25], "transparent_lenses": False},
}


def build_lod(mid, level):
    """Build one LOD of a car; returns the Model."""
    Q.use(level)
    try:
        return importlib.import_module(f"cars.{mid}").build()
    finally:
        Q.use(0)


def build_one(mid):
    folder = os.path.join(OUT, mid)
    os.makedirs(folder, exist_ok=True)
    lods = []
    for level in (1, 2):
        lm = build_lod(mid, level)
        glb, st = lm._build_glb()
        name = f"{mid}_lod{level}.glb"
        with open(os.path.join(folder, name), "wb") as f:
            f.write(glb)
        lods.append((level, name, st))
    model = build_lod(mid, 0)
    stats = model.write(folder)
    lods.insert(0, (0, mid + ".glb", stats))
    rig_path = os.path.join(folder, mid + ".rig.json")
    with open(rig_path, encoding="utf-8") as f:
        rig = json.load(f)
    rig["lods"] = [{"level": lv, "glb": name, "triangles": st["triangles"], "bytes": st["bytes"],
                    "chord_tolerance_mm": round(Q.LODS[lv]["tol"] * 1000, 2), "use": Q.LODS[lv]["use"]}
                   for lv, name, st in lods]
    rig["lod_note"] = ("Every LOD has the same nodes, pivots, joints and material names (only the tessellation and "
                       "the small detail differ), so a LOD swaps per node mesh; the rig, flow and cockpit sidecars "
                       "describe all three. Generated by tools/cargen (cargen/quality.py).")
    rig["quality_tiers"] = QUALITY_TIERS
    write_json(rig_path, rig)
    stats["lods"] = [(lv, st["triangles"], st["bytes"]) for lv, _, st in lods]
    with open(os.path.join(folder, mid + ".glb"), "rb") as f:
        sha = hashlib.sha256(f.read()).hexdigest()
    sel = dict(model.flow_selection)
    sel["source_glb_sha256"] = sha
    write_json(os.path.join(folder, mid + ".flow.json"), sel)
    cockpit = dict(model.cockpit)
    cockpit["source_glb_sha256"] = sha
    write_json(os.path.join(folder, mid + ".cockpit.json"), cockpit)
    return stats


def main(argv):
    ids = argv or MODELS
    unknown = [i for i in ids if i not in MODELS]
    if unknown:
        sys.exit(f"unknown model(s): {unknown}; known: {MODELS}")
    for mid in ids:
        t0 = time.time()
        s = build_one(mid)
        print(f"{mid:12s} {s['triangles']:7d} tris  {s['nodes']:3d} nodes  {s['materials']:3d} mats  "
              f"{s['images']:3d} imgs  {s['bytes'] / 1e6:6.2f} MB  {time.time() - t0:5.1f} s  | " +
              "  ".join(f"lod{lv} {t} tris {b / 1e6:.2f} MB" for lv, t, b in s["lods"]))
    index = []
    for mid in MODELS:
        rig = os.path.join(OUT, mid, mid + ".rig.json")
        if os.path.exists(rig):
            with open(rig, encoding="utf-8") as f:
                title = json.load(f)["title"]
            index.append({"id": mid, "title": title, "glb": f"{mid}/{mid}.glb", "rig": f"{mid}/{mid}.rig.json",
                          "flow": f"{mid}/{mid}.flow.json", "cockpit": f"{mid}/{mid}.cockpit.json"})
    write_json(os.path.join(OUT, "index.json"), index)


if __name__ == "__main__":
    main(sys.argv[1:])
